import streamlit as st

st.set_page_config(page_title="口径说明", page_icon="📖", layout="wide")

st.title("📖 口径说明 · 常见问题")
st.caption("看懂看板：起始日、调仓规则、收益怎么算。想看某人的逐日明细，去左侧「投资者明细」页。")

# ------------------------------------------------------------------ 1 起始日
st.header("1. 收益计算起始日")
st.markdown(
    """
- 所有投资者的**统一起始日** = `start_date`（当前 `2026-09-24`）。
- **起始日当天 = 本金 100 万**（基准），大家从这里起步；**只展示起始日及之后**的点。
"""
)

# ------------------------------------------------------------------ 2 口径
st.header("2. 收益口径")
st.markdown(
    """
- 用**未复权收盘价**的**价格收益**：**不含分红 / 除权**，**不计汇率**。
- ⚠️ 因此跨**除权除息**（A股）或**拆股**（美股）会有跳空，适合近期窗口。
"""
)

# ------------------------------------------------------------------ 3 调仓规则
st.header("3. 调仓规则")
st.markdown(
    """
- 每位投资者持有一条**持仓路径**：可以**全仓切换**标的（从标的 1 整体换到标的 2）。
- **切换时点**：调仓日按**当日收盘价**整体换仓；**当天算旧标的，次交易日起算新标的**。
- 调仓日**逢非交易日** → 顺延到下一交易日。
- **不计费用 / 滑点**，**不计汇率**。
- 同一投资者**同日多条调仓时，最后一条生效**。
"""
)

# ------------------------------------------------------------------ 4 公式
st.header("4. 累计收益怎么算")
st.markdown("把持仓路径上**各段的标的收益连乘**（复利）：")
st.latex(
    r"价值(t) = 本金 \times \prod_{\text{已结束段}} R_j \;\times\;"
    r" \frac{P_{\text{当前段}}(t)}{P_{\text{当前段}}(\text{段起点})}"
)
st.latex(r"其中每段收益 \quad R_j = \frac{P_j(\text{下段起点})}{P_j(\text{本段起点})}")
st.markdown("累计收益率 = 价值(t) / 本金 − 1。起始日当天，价值 = 本金（即 0%）。")

st.divider()

# ------------------------------------------------------------------ 5 数字示例
st.header("5. 数字示例：Alice 4 天调 2 次仓（A股 → 美股 → 港股）")
st.markdown(
    """
**设定**：本金 **100 万**；**起始日`2026-09-24`持有 A股 A（起始日不调仓）**；
第 2 天 `2026-09-25` **收盘调仓 A → B**（美股）；第 3 天 `2026-09-28` **收盘调仓 B → C**（港股）。

| 交易日 | 当日在手标的 | 当天发出调仓 | 收盘价 | 当日市值 | 说明 |
|---|---|---|---|---|---|
| `2026-09-24`（第1天） | A股 **A** | —（起始日，不调仓） | A = 10.00 | **100.0 万** | 起始日 = 基准 |
| `2026-09-25`（第2天） | A股 **A** | ✅ A → **B**（美股） | A = 11.00 | **110.0 万** | 调仓当日**仍按旧标的 A** 计收益；收盘换到 B（B=100.00 作新基准） |
| `2026-09-28`（第3天） | 美股 **B** | ✅ B → **C**（港股） | B = 110.00 | **121.0 万** | 调仓当日**仍按旧标的 B** 计收益；收盘换到 C（C=50.00 作新基准） |
| `2026-09-29`（第4天） | 港股 **C** | — | C = 55.00 | **133.1 万** | 持 C |
"""
)

st.markdown("**分步计算：**")
st.markdown(
    """
1. `2026-09-24`（持 A，起始基准）：`100万 × A(09-24)/A(09-24) = 100万`
2. `2026-09-25`（持 A；**当天发出 A→B，仍按 A**）：`100万 × A(09-25)/A(09-24) = 100万 × 11/10 = 110万`
3. `2026-09-28`（持 B；**当天发出 B→C，仍按 B**）：`110万 × B(09-28)/B(09-25) = 110万 × 110/100 = 121万`
4. `2026-09-29`（持 C）：`121万 × C(09-29)/C(09-28) = 121万 × 55/50 = 133.1万`
"""
)
st.latex(r"\text{累计收益率} = \frac{11}{10}\times\frac{110}{100}\times\frac{55}{50} - 1 "
         r"= 1.10 \times 1.10 \times 1.10 - 1 = +33.1\%")

st.info("关键：**发出/执行调仓的当天，仍按旧标的计算收益**（上例 09-25 当天算 A、09-28 当天算 B）；"
        "新标的的收益从**次交易日**才开始累积。")

st.caption("看板上的每个人就是按上面这套规则，从 100 万一路连乘出来的；"
           "「投资者明细」页可看到逐日持有标的与当日收益。")
